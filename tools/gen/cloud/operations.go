package main

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
)

// EmitOperations renders the live operation table: the generated proof of what a
// hand-written service still has to cover, and the spec's own base URL.
func EmitOperations(doc map[string]any, pkg string) ([]byte, error) {
	schemas, ok := dig(doc, "components", "schemas")
	if !ok {
		return nil, fmt.Errorf("no components.schemas")
	}
	names := schemaNames(schemas)
	paths, ok := doc["paths"].(map[string]any)
	if !ok {
		return nil, fmt.Errorf("no paths")
	}

	base := ""
	if servers, ok := doc["servers"].([]any); ok && len(servers) > 0 {
		if m, ok := servers[0].(map[string]any); ok {
			base, _ = m["url"].(string)
		}
	}

	keys := make([]string, 0, len(paths))
	for k := range paths {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/gen/cloud from the iikoCloud OpenAPI spec. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	fmt.Fprintf(&b, "// DefaultBaseURL comes from the spec's servers block, which is injected by an overlay.\n")
	fmt.Fprintf(&b, "const DefaultBaseURL = %q\n\n", base)
	fmt.Fprintf(&b, "// Operation is one live iikoCloud endpoint. Deprecated ones are not generated.\n")
	fmt.Fprintf(&b, "type Operation struct {\n\tPath     string\n\tTag      string\n\tSummary  string\n\tRequest  string\n\tResponse string\n}\n\n")
	fmt.Fprintf(&b, "// Operations lists every non-deprecated operation in the spec.\nvar Operations = []Operation{\n")

	for _, p := range keys {
		item, _ := paths[p].(map[string]any)
		for _, method := range []string{"post", "get", "put", "delete", "patch"} {
			op, ok := item[method].(map[string]any)
			if !ok || op["deprecated"] == true {
				continue
			}
			tag := ""
			if tags, ok := op["tags"].([]any); ok && len(tags) > 0 {
				tag = fmt.Sprint(tags[0])
			}
			summary, _ := op["summary"].(string)
			fmt.Fprintf(&b, "\t{Path: %q, Tag: %q, Summary: %q, Request: %q, Response: %q},\n",
				p, tag, oneLine(summary), names[bodyRef(op, "requestBody")], goResponse(op, names))
		}
	}
	fmt.Fprintf(&b, "}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		return b.Bytes(), fmt.Errorf("generated source does not parse: %w", err)
	}
	return src, nil
}

// goResponse names the 200 body, including the sixteen operations that answer
// with a bare array rather than a named wrapper.
func goResponse(op map[string]any, names map[string]string) string {
	sc := bodySchema(op, "responses")
	if sc == nil {
		return ""
	}
	if k := refKey(sc); k != "" {
		return names[k]
	}
	if t, _ := sc["type"].(string); t == "array" {
		items, _ := sc["items"].(map[string]any)
		if k := refKey(items); k != "" {
			return "[]" + names[k]
		}
	}
	return ""
}

// bodyRef finds the JSON schema key of an operation's request or 200 response.
func bodyRef(op map[string]any, where string) string {
	return refKey(bodySchema(op, where))
}

func bodySchema(op map[string]any, where string) map[string]any {
	node, _ := op[where].(map[string]any)
	if where == "responses" {
		node, _ = node["200"].(map[string]any)
	}
	content, _ := node["content"].(map[string]any)
	js, _ := content["application/json"].(map[string]any)
	sc, _ := js["schema"].(map[string]any)
	return sc
}
