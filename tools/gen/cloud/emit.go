package main

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strings"
)

// Emit renders every component schema of an overlaid spec as Go declarations.
func Emit(doc map[string]any, pkg string) ([]byte, error) {
	schemas, ok := dig(doc, "components", "schemas")
	if !ok {
		return nil, fmt.Errorf("no components.schemas")
	}
	e := &emitter{schemas: schemas, names: schemaNames(schemas)}

	keys := make([]string, 0, len(schemas))
	for k := range schemas {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool { return e.names[keys[i]] < e.names[keys[j]] })

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/gen/cloud from the iikoCloud OpenAPI spec. DO NOT EDIT.\n\n")
	// The package comment lives in doc.go; a second one here would split godoc.
	fmt.Fprintf(&b, "package %s\n\nimport \"encoding/json\"\n\nvar _ = json.RawMessage{}\n\n", pkg)
	for _, k := range keys {
		e.declare(&b, k)
	}

	src, err := format.Source(b.Bytes())
	if err != nil {
		return b.Bytes(), fmt.Errorf("generated source does not parse: %w", err)
	}
	return src, nil
}

type emitter struct {
	schemas map[string]any
	names   map[string]string
}

func (e *emitter) declare(b *bytes.Buffer, key string) {
	s, _ := e.schemas[key].(map[string]any)
	name := e.names[key]
	if d, _ := s["description"].(string); d != "" {
		fmt.Fprintf(b, "// %s %s\n", name, oneLine(d))
	}

	switch {
	case s["enum"] != nil:
		e.declareEnum(b, name, s)
	case isStruct(s):
		e.declareStruct(b, name, s)
	default:
		fmt.Fprintf(b, "type %s %s\n\n", name, e.goType(s))
	}
}

func (e *emitter) declareEnum(b *bytes.Buffer, name string, s map[string]any) {
	base := "string"
	if t, _ := s["type"].(string); t == "integer" {
		base = "int"
	}
	fmt.Fprintf(b, "type %s %s\n\nconst (\n", name, base)
	for _, v := range s["enum"].([]any) {
		if base == "int" {
			fmt.Fprintf(b, "\t%s%v %s = %v\n", name, v, name, v)
			continue
		}
		fmt.Fprintf(b, "\t%s%s %s = %q\n", name, exported(fmt.Sprint(v)), name, v)
	}
	fmt.Fprintf(b, ")\n\n")
}

func (e *emitter) declareStruct(b *bytes.Buffer, name string, s map[string]any) {
	fmt.Fprintf(b, "type %s struct {\n", name)
	for _, parent := range embedded(s) {
		fmt.Fprintf(b, "\t%s\n", e.names[refKey(parent)])
	}
	props, _ := s["properties"].(map[string]any)
	req := requiredSet(s)
	keys := make([]string, 0, len(props))
	for k := range props {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		p, _ := props[k].(map[string]any)
		tag := k
		if !req[k] {
			tag += ",omitempty"
		}
		if d, _ := p["description"].(string); d != "" {
			fmt.Fprintf(b, "\t// %s\n", oneLine(d))
		}
		fmt.Fprintf(b, "\t%s %s `json:%q`\n", exported(k), e.goType(p), tag)
	}
	fmt.Fprintf(b, "}\n\n")
}

// goType maps one schema node to a Go type expression.
func (e *emitter) goType(s map[string]any) string {
	if s == nil {
		return "json.RawMessage"
	}
	if k := refKey(s); k != "" {
		if e.isPolymorphic(k) {
			return "json.RawMessage"
		}
		return e.names[k]
	}
	// An allOf of one $ref with sibling annotations is just that reference.
	if all, ok := s["allOf"].([]any); ok && len(all) == 1 && !isStruct(s) {
		if m, ok := all[0].(map[string]any); ok {
			return e.goType(m)
		}
	}
	if one, ok := s["oneOf"].([]any); ok {
		if len(one) == 1 {
			if m, ok := one[0].(map[string]any); ok {
				return e.goType(m)
			}
		}
		return "json.RawMessage"
	}
	switch t, _ := s["type"].(string); t {
	case "string":
		return "string"
	case "boolean":
		return "bool"
	case "number":
		return "float64"
	case "integer":
		if f, _ := s["format"].(string); f == "int64" {
			return "int64"
		}
		return "int"
	case "array":
		items, _ := s["items"].(map[string]any)
		return "[]" + e.goType(items)
	case "object":
		if ap, ok := s["additionalProperties"].(map[string]any); ok {
			if len(ap) == 0 {
				return "map[string]json.RawMessage"
			}
			return "map[string]" + e.goType(ap)
		}
		if isStruct(s) {
			// Inline objects are rare enough that a raw payload beats a synthetic name.
			return "json.RawMessage"
		}
		return "json.RawMessage"
	default:
		return "json.RawMessage"
	}
}

// isPolymorphic reports whether a referenced schema is a discriminated base.
func (e *emitter) isPolymorphic(key string) bool {
	s, _ := e.schemas[key].(map[string]any)
	return s != nil && s["discriminator"] != nil
}

func isStruct(s map[string]any) bool {
	if s["properties"] != nil {
		return true
	}
	_, all := s["allOf"]
	t, _ := s["type"].(string)
	return all && t == "object"
}

// embedded returns the allOf parents a struct inherits from.
func embedded(s map[string]any) []map[string]any {
	if !isStruct(s) {
		return nil
	}
	all, _ := s["allOf"].([]any)
	var out []map[string]any
	for _, a := range all {
		if m, ok := a.(map[string]any); ok && refKey(m) != "" {
			out = append(out, m)
		}
	}
	return out
}

func refKey(s map[string]any) string {
	if s == nil {
		return ""
	}
	r, _ := s["$ref"].(string)
	return strings.TrimPrefix(r, "#/components/schemas/")
}

func requiredSet(s map[string]any) map[string]bool {
	out := map[string]bool{}
	r, _ := s["required"].([]any)
	for _, v := range r {
		out[fmt.Sprint(v)] = true
	}
	return out
}

func dig(m map[string]any, keys ...string) (map[string]any, bool) {
	cur := m
	for _, k := range keys {
		next, ok := cur[k].(map[string]any)
		if !ok {
			return nil, false
		}
		cur = next
	}
	return cur, true
}

func oneLine(s string) string {
	s = strings.NewReplacer("\r", " ", "\n", " ", "\t", " ").Replace(s)
	for strings.Contains(s, "  ") {
		s = strings.ReplaceAll(s, "  ", " ")
	}
	if len(s) > 160 {
		s = s[:160] + "…"
	}
	return strings.TrimSpace(s)
}
