package main

import (
	"bytes"
	"fmt"
	"sort"
	"strings"
)

// initialisms Go capitalises wholesale; without this productId becomes ProductId.
var initialisms = map[string]string{
	"id": "ID", "uuid": "UUID", "url": "URL", "api": "API", "vat": "VAT",
	"nds": "NDS", "gln": "GLN", "inn": "INN", "kpp": "KPP", "edi": "EDI",
	"olap": "OLAP", "xml": "XML", "json": "JSON", "http": "HTTP", "sku": "SKU",
	"rms": "RMS", "pos": "POS", "ip": "IP", "db": "DB",
}

// goName turns an iiko field name into an exported Go identifier.
func goName(s string) string {
	parts := splitWords(s)
	var b strings.Builder
	for _, p := range parts {
		if up, ok := initialisms[strings.ToLower(p)]; ok {
			b.WriteString(up)
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	n := b.String()
	if n == "" {
		return "Field"
	}
	return n
}

// splitWords breaks camelCase, snake_case and dotted names into words.
func splitWords(s string) []string {
	s = strings.NewReplacer("_", " ", ".", " ", "-", " ").Replace(s)
	var out []string
	for _, chunk := range strings.Fields(s) {
		start := 0
		for i := 1; i < len(chunk); i++ {
			if chunk[i] >= 'A' && chunk[i] <= 'Z' && chunk[i-1] >= 'a' && chunk[i-1] <= 'z' {
				out = append(out, chunk[start:i])
				start = i
			}
		}
		out = append(out, chunk[start:])
	}
	return out
}

// goType maps a catalog type to Go. Dates stay strings: iiko emits six layouts
// and responses vary even within one endpoint, so rest.ParseFlexible decides.
// declaredKind tells goType what a referenced name resolves to in this package.
type declaredKind int

const (
	kindMissing declaredKind = iota // skipped, or owned by another package
	kindStruct
	kindEnum // an enum-only DTO: a string in the wire format
)

func goType(f field, known map[string]declaredKind, xmlDoc bool) string {
	switch f.Type {
	case "int":
		return "int"
	case "decimal":
		return "float64"
	case "bool":
		return "bool"
	case "array":
		// `of` may name a primitive rather than a DTO.
		if prim := primitiveOf(f.Of); prim != "" {
			return "[]" + prim
		}
		switch known[f.Of] {
		case kindStruct:
			return "[]" + f.Of
		case kindEnum:
			return "[]string"
		}
		if f.Of == "" || xmlDoc {
			return "[]string" // encoding/xml has no RawMessage equivalent
		}
		return "[]json.RawMessage" // element type lives elsewhere or is not generated
	case "object":
		// map_of wins over of: a field carrying both is a map, and `of` is the
		// value type the catalog recorded before the distinction existed.
		if f.MapOf != "" {
			return "map[string]" + elementType(f.MapOf, known, xmlDoc)
		}
		if prim := primitiveOf(f.Of); prim != "" {
			return prim
		}
		switch known[f.Of] {
		case kindStruct:
			return f.Of
		case kindEnum:
			return "string"
		}
		if xmlDoc {
			return "string"
		}
		return "json.RawMessage"
	default: // string, uuid, enum, date, datetime, text
		return "string"
	}
}

func render(pkg string, dtos []dto) ([]byte, error) {
	sort.Slice(dtos, func(i, j int) bool { return dtos[i].Name < dtos[j].Name })

	var b bytes.Buffer
	fmt.Fprint(&b, "// Code generated by tools/gen/server from research/dtos.yaml. DO NOT EDIT.\n\n")
	fmt.Fprint(&b, "// Field names, types and the read-only and alias marks all come from the\n")
	fmt.Fprint(&b, "// catalog; change research/dtos.yaml and re-run `make gen`, never this file.\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)

	known := map[string]declaredKind{}
	for _, d := range dtos {
		hasField := false
		for _, f := range d.Fields {
			if !f.Unimplement {
				hasField = true
				break
			}
		}
		if hasField {
			known[d.Name] = kindStruct
		} else {
			known[d.Name] = kindEnum
		}
	}

	body := &bytes.Buffer{}
	taken := map[string]bool{}
	for _, d := range dtos {
		declare(body, d, taken, known)
	}
	// Read the imports off the emitted text: several paths can introduce a
	// package, and a flag per path drifts out of sync with them.
	var imports []string
	if strings.Contains(body.String(), "json.") {
		imports = append(imports, "encoding/json")
	}
	if strings.Contains(body.String(), "reflect.") {
		imports = append(imports, "reflect")
	}
	if len(imports) > 0 {
		fmt.Fprint(&b, "import (\n")
		for _, i := range imports {
			fmt.Fprintf(&b, "\t%q\n", i)
		}
		fmt.Fprint(&b, ")\n\n")
	}
	b.Write(body.Bytes())
	return formatSrc(b.Bytes())
}

// declare writes one DTO, reporting whether it needed encoding/json and isZero.
func declare(b *bytes.Buffer, d dto, taken map[string]bool, known map[string]declaredKind) {
	tagKey := "json"
	xmlDoc := d.Format == "xml"
	if xmlDoc {
		tagKey = "xml"
	}

	for _, e := range d.Enums {
		writeEnum(b, d, e, taken)
	}

	var kept []field
	for _, f := range d.Fields {
		if f.Unimplement {
			continue // documented but the server ignores it
		}
		kept = append(kept, f)
	}
	if len(kept) == 0 {
		return
	}

	if note := firstLine(d.Notes); note != "" {
		fmt.Fprintf(b, "// %s is %s\n", d.Name, note)
	} else {
		fmt.Fprintf(b, "// %s mirrors the iiko DTO of the same name.\n", d.Name)
	}
	fmt.Fprintf(b, "type %s struct {\n", d.Name)
	var readOnly, aliased []field
	for _, f := range kept {
		name := goName(f.Name)
		tag := fieldTag(f, xmlDoc)
		gt := goType(f, known, xmlDoc)
		fmt.Fprintf(b, "\t%s %s `%s:\"%s\"`", name, gt, tagKey, tag)
		if c := fieldComment(f); c != "" {
			fmt.Fprintf(b, " // %s", c)
		}
		fmt.Fprint(b, "\n")
		if f.ReadOnly {
			readOnly = append(readOnly, f)
		}
		if len(f.Aliases) > 0 {
			aliased = append(aliased, f)
		}
	}
	fmt.Fprint(b, "}\n\n")

	if len(aliased) > 0 && tagKey == "json" {
		writeUnmarshal(b, d, aliased, known, xmlDoc)
	}
	if len(readOnly) > 0 && len(readOnly) < len(kept) {
		// Every field read-only means the DTO is a response and is never sent;
		// a MarshalJSON that always yields {} would be a trap, not a guard.
		if tagKey == "json" {
			writeMarshal(b, d, kept, readOnly, known, xmlDoc)
		} else {
			writeStrip(b, d, readOnly, known, xmlDoc)
		}
	}
}

func fieldComment(f field) string {
	var marks []string
	if f.ReadOnly {
		marks = append(marks, "read-only")
	}
	if v := f.enumValues(); len(v) > 1 {
		marks = append(marks, strings.Join(v, " "))
	}
	if len(f.Aliases) > 0 {
		marks = append(marks, "also spelled "+strings.Join(f.Aliases, ", "))
	}
	return strings.Join(marks, "; ")
}

func firstLine(v any) string {
	s := strings.TrimSpace(strings.ReplaceAll(asString(v), "\n", " "))
	if len(s) > 110 {
		s = s[:110] + "…"
	}
	return s
}

func writeEnum(b *bytes.Buffer, d dto, e enumDef, taken map[string]bool) {
	if len(e.Values) == 0 {
		return
	}
	// Catalog enum names are prose ("ProductType_enum (legacy XML)"), not identifiers.
	name := d.Name + goIdent(e.Name) + "Values"
	if taken[name] {
		return
	}
	taken[name] = true
	fmt.Fprintf(b, "// %s are the documented values of %s.%s.\n", name, d.Name, e.Name)
	fmt.Fprintf(b, "var %s = []string{\n", name)
	for _, v := range e.Values {
		fmt.Fprintf(b, "\t%q,\n", v)
	}
	fmt.Fprint(b, "}\n\n")
}

// writeUnmarshal accepts every documented spelling of a field the docs spell
// more than one way; the catalog's primary name wins when both are present.
func writeUnmarshal(b *bytes.Buffer, d dto, aliased []field, known map[string]declaredKind, xmlDoc bool) {
	fmt.Fprintf(b, "// UnmarshalJSON accepts every documented spelling of %s's ambiguous fields.\n",
		d.Name)
	fmt.Fprintf(b, "func (x *%s) UnmarshalJSON(data []byte) error {\n", d.Name)
	fmt.Fprintf(b, "\ttype plain %s\n", d.Name)
	fmt.Fprint(b, "\tvar v struct {\n\t\tplain\n")
	for i, f := range aliased {
		for j, a := range f.Aliases {
			fmt.Fprintf(b, "\t\tAlias%d_%d %s `json:%q`\n", i, j, goType(f, known, xmlDoc), a)
		}
	}
	fmt.Fprint(b, "\t}\n")
	fmt.Fprintf(b, "\tif err := json.Unmarshal(data, &v); err != nil {\n\t\treturn err\n\t}\n")
	fmt.Fprintf(b, "\t*x = %s(v.plain)\n", d.Name)
	for i, f := range aliased {
		name := goName(f.Name)
		for j := range f.Aliases {
			fmt.Fprintf(b, "\tif %s {\n\t\tx.%s = v.Alias%d_%d\n\t}\n", absentTest("x."+name, goType(f, known, xmlDoc)), name, i, j)
		}
	}
	fmt.Fprint(b, "\treturn nil\n}\n\n")
}

// writeMarshal drops server-generated fields on the way out: re-sending an
// exported document with them is rejected.
func writeMarshal(b *bytes.Buffer, d dto, kept, readOnly []field, known map[string]declaredKind, xmlDoc bool) {
	ro := map[string]bool{}
	for _, f := range readOnly {
		ro[f.Name] = true
	}
	fmt.Fprintf(b, "// MarshalJSON omits the read-only fields iiko rejects on the way in.\n")
	fmt.Fprintf(b, "func (x %s) MarshalJSON() ([]byte, error) {\n", d.Name)
	fmt.Fprint(b, "\treturn json.Marshal(struct {\n")
	for _, f := range kept {
		if ro[f.Name] {
			continue
		}
		tag := f.Name
		if f.Required == nil || !*f.Required {
			tag += ",omitempty"
		}
		fmt.Fprintf(b, "\t\t%s %s `json:\"%s\"`\n", goName(f.Name), goType(f, known, xmlDoc), tag)
	}
	fmt.Fprint(b, "\t}{\n")
	for _, f := range kept {
		if ro[f.Name] {
			continue
		}
		fmt.Fprintf(b, "\t\t%s: x.%s,\n", goName(f.Name), goName(f.Name))
	}
	fmt.Fprint(b, "\t})\n}\n\n")
}

// writeStrip is the XML counterpart: encoding/xml has no per-field skip hook, so
// callers zero the read-only fields before re-sending an exported document.
func writeStrip(b *bytes.Buffer, d dto, readOnly []field, known map[string]declaredKind, xmlDoc bool) {
	fmt.Fprintf(b, "// StripReadOnly zeroes the server-generated fields. Call it before re-sending\n")
	fmt.Fprintf(b, "// an exported %s: encoding/xml cannot skip them per field.\n", d.Name)
	fmt.Fprintf(b, "func (x *%s) StripReadOnly() {\n", d.Name)
	for _, f := range readOnly {
		fmt.Fprintf(b, "\tvar zero%s %s\n", goName(f.Name), goType(f, known, xmlDoc))
		fmt.Fprintf(b, "\tx.%s = zero%s\n", goName(f.Name), goName(f.Name))
	}
	fmt.Fprint(b, "}\n\n")
}

// goIdent strips everything that cannot appear in a Go identifier.
func goIdent(s string) string {
	var b strings.Builder
	upper := true
	for _, r := range s {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9':
			if upper {
				b.WriteString(strings.ToUpper(string(r)))
				upper = false
			} else {
				b.WriteRune(r)
			}
		default:
			upper = true
		}
	}
	return b.String()
}

// absentTest renders "this field carries nothing", per type: a slice is empty, a
// struct is compared deeply, everything else is its zero value.
func absentTest(expr, typ string) string {
	switch {
	case strings.HasPrefix(typ, "[]"):
		return "len(" + expr + ") == 0"
	case typ == "string":
		return expr + ` == ""`
	case typ == "int":
		return expr + " == 0"
	case typ == "float64":
		return expr + " == 0"
	case typ == "bool":
		return "!" + expr
	default:
		return "reflect.DeepEqual(" + expr + ", " + typ + "{})"
	}
}

// primitiveOf maps a catalog `of` naming a primitive to its Go type; "" when it
// names a DTO instead.
func primitiveOf(of string) string {
	switch of {
	case "string", "uuid", "date", "datetime", "enum", "text":
		return "string"
	case "int":
		return "int"
	case "decimal":
		return "float64"
	case "bool":
		return "bool"
	default:
		return ""
	}
}

// elementType resolves a map's or array's value type: a primitive, a generated
// DTO, an enum-only DTO (a string on the wire), or an unresolvable reference.
func elementType(name string, known map[string]declaredKind, xmlDoc bool) string {
	if prim := primitiveOf(name); prim != "" {
		return prim
	}
	switch known[name] {
	case kindStruct:
		return name
	case kindEnum:
		return "string"
	}
	if xmlDoc {
		return "string"
	}
	return "json.RawMessage"
}

// fieldTag builds the struct tag value. The catalog's field tables cannot tell
// an XML attribute from an element, so attr/chardata/wrapper are marked
// explicitly; without them a real <order number="..."> parses into an empty
// struct and never errors.
func fieldTag(f field, xmlDoc bool) string {
	optional := f.Required == nil || !*f.Required
	if xmlDoc {
		switch f.XML {
		case "attr":
			// An optional attribute must be omitted when unset: an empty
			// attribute on a document's identity key can stop iiko matching it.
			if optional {
				return f.Name + ",attr,omitempty"
			}
			return f.Name + ",attr"
		case "chardata":
			return ",chardata"
		}
		if f.Wrapper != "" {
			return f.Name + ">" + f.Wrapper
		}
	}
	if optional {
		return f.Name + ",omitempty"
	}
	return f.Name
}
