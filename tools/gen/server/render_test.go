func TestGoNameKeepsInitialismsWhole(t *testing.T) {
	t.Parallel()
	tests := []struct{ in, want string }{
		{"id", "ID"},
		{"productId", "ProductID"},
		{"dateIncoming", "DateIncoming"},
		{"accountParentId", "AccountParentID"},
		{"vatPercent", "VATPercent"},
		{"DateTime.Typed", "DateTimeTyped"},
		{"snils", "Snils"},
		{"fsRarId", "FsRarID"},
	}
	for _, tt := range tests {
		t.Run(tt.in, func(t *testing.T) {
			t.Parallel()
			if got := goName(tt.in); got != tt.want {
				t.Errorf("goName(%q) = %q, want %q", tt.in, got, tt.want)
			}
		})
	}
}

func TestGoIdentStripsProse(t *testing.T) {
	t.Parallel()
	// Catalog enum names are prose, not identifiers.
	if got := goIdent("ProductType_enum (legacy XML)"); got != "ProductTypeEnumLegacyXML" {
		t.Errorf("goIdent = %q", got)
	}
}

func TestGoTypeFallsBackByFormat(t *testing.T) {
	t.Parallel()
	known := map[string]declaredKind{"ChildDto": kindStruct, "SomeEnum": kindEnum}
	tests := []struct {
		name   string
		f      field
		xmlDoc bool
		want   string
	}{
		{name: "known struct", f: field{Type: "object", Of: "ChildDto"}, want: "ChildDto"},
		{name: "enum-only DTO is a string", f: field{Type: "object", Of: "SomeEnum"}, want: "string"},
		{name: "array of known struct", f: field{Type: "array", Of: "ChildDto"}, want: "[]ChildDto"},
		{name: "unknown element in JSON", f: field{Type: "array", Of: "Gone"}, want: "[]json.RawMessage"},
		// `of` names a primitive as often as it names a DTO.
		{name: "array of primitive strings", f: field{Type: "array", Of: "string"}, want: "[]string"},
		{name: "array of uuids is a string slice", f: field{Type: "array", Of: "uuid"}, want: "[]string"},
		{name: "array of decimals", f: field{Type: "array", Of: "decimal"}, want: "[]float64"},
		// map_of is a map keyed by a name the docs do not enumerate.
		{name: "map of DTO", f: field{Type: "object", MapOf: "ChildDto"}, want: "map[string]ChildDto"},
		{name: "map of primitive", f: field{Type: "object", MapOf: "string"}, want: "map[string]string"},
		{name: "map_of beats of", f: field{Type: "object", Of: "ChildDto", MapOf: "SomeEnum"}, want: "map[string]string"},
		{name: "map of unknown DTO", f: field{Type: "object", MapOf: "Gone"}, want: "map[string]json.RawMessage"},
		// encoding/xml has no RawMessage, so an XML DTO must never get one.
		{name: "unknown element in XML", f: field{Type: "array", Of: "Gone"}, xmlDoc: true, want: "[]string"},
		{name: "unknown object in XML", f: field{Type: "object", Of: "Gone"}, xmlDoc: true, want: "string"},
		{name: "decimal", f: field{Type: "decimal"}, want: "float64"},
		{name: "dates stay strings", f: field{Type: "datetime"}, want: "string"},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()
			if got := goType(tt.f, known, tt.xmlDoc); got != tt.want {
				t.Errorf("goType = %q, want %q", got, tt.want)
			}
		})
	}
}

func TestAbsentTestMatchesTheType(t *testing.T) {
	t.Parallel()
	tests := []struct{ typ, want string }{
		{"string", `x.F == ""`},
		{"int", "x.F == 0"},
		{"bool", "!x.F"},
		{"[]Thing", "len(x.F) == 0"},
		{"Thing", "reflect.DeepEqual(x.F, Thing{})"},
	}
	for _, tt := range tests {
		t.Run(tt.typ, func(t *testing.T) {
			t.Parallel()
			if got := absentTest("x.F", tt.typ); got != tt.want {
				t.Errorf("absentTest(%q) = %q, want %q", tt.typ, got, tt.want)
			}
		})
	}
}

func yes() *bool { b := true; return &b }

// The three catalog marks that change generated code: read_only, aliases and
// declared_but_unimplemented.
func TestRenderHonoursTheCatalogMarks(t *testing.T) {
	t.Parallel()
	d := dto{
		Name: "SampleDto", Format: "json",
		Fields: []field{
			{Name: "id", Type: "uuid", ReadOnly: true, Required: yes()},
			{Name: "amount", Type: "decimal", Required: yes()},
			{Name: "status", Type: "string", Aliases: []string{"staus"}},
			{Name: "ghost", Type: "string", Unimplement: true},
		},
	}
	src, err := render("sample", []dto{d})
	if err != nil {
		t.Fatalf("render: %v", err)
	}
	got := string(src)

	if _, err := parser.ParseFile(token.NewFileSet(), "types.go", got, 0); err != nil {
		t.Fatalf("generated code does not parse: %v\n%s", err, got)
	}
	if !strings.HasPrefix(got, "// Code generated by tools/gen/server") || !strings.Contains(got, "DO NOT EDIT") {
		t.Error("the generated header must mark the file as generated")
	}
	// declared_but_unimplemented is not generated at all
	if strings.Contains(got, "Ghost") {
		t.Error("a declared-but-unimplemented field must not be generated")
	}
	// read_only is readable but never sent
	// gofmt pads struct fields for alignment, so match the parts, not the spacing.
	if !regexp.MustCompile(`ID\s+string\s+` + "`" + `json:"id"` + "`").MatchString(got) {
		t.Errorf("a read-only field must still decode; got:\n%s", got)
	}
	if !strings.Contains(got, "func (x SampleDto) MarshalJSON()") {
		t.Fatal("a DTO with read-only fields needs a MarshalJSON that omits them")
	}
	marshal := got[strings.Index(got, "MarshalJSON"):]
	if strings.Contains(marshal, `json:"id"`) {
		t.Error("MarshalJSON must not send the read-only id")
	}
	if !strings.Contains(marshal, `json:"amount"`) {
		t.Error("MarshalJSON must still send writable fields")
	}
	// both documented spellings decode
	if !strings.Contains(got, `json:"staus"`) || !strings.Contains(got, "UnmarshalJSON") {
		t.Error("an aliased field needs an UnmarshalJSON accepting every spelling")
	}
}

// A DTO whose every field is read-only is a response and is never sent; a
// MarshalJSON emitting {} would silently drop everything.
func TestRenderSkipsMarshalWhenNothingIsWritable(t *testing.T) {
	t.Parallel()
	d := dto{Name: "ReadOnlyDto", Format: "json", Fields: []field{
		{Name: "a", Type: "string", ReadOnly: true},
		{Name: "b", Type: "string", ReadOnly: true},
	}}
	src, err := render("sample", []dto{d})
	if err != nil {
		t.Fatalf("render: %v", err)
	}
	if strings.Contains(string(src), "MarshalJSON") {
		t.Error("a fully read-only DTO must not get a MarshalJSON that yields {}")
	}
}

// The catalog's field tables cannot tell an XML attribute from an element, so
// the mark is explicit. Getting it wrong parses a real <order number="..."> into
// an empty struct without erroring.
func TestRenderHonoursXMLAttributeAndWrapperMarks(t *testing.T) {
	t.Parallel()
	yes := true
	d := dto{Name: "OrderDto", Format: "xml", Fields: []field{
		{Name: "number", Type: "string", XML: "attr", Required: &yes},
		{Name: "date", Type: "string", XML: "attr", Required: &yes},
		{Name: "kind", Type: "string", XML: "attr"}, // optional
		{Name: "comment", Type: "string"},
		{Name: "text", Type: "string", XML: "chardata"},
		{Name: "lineItems", Type: "array", Of: "ItemDto", Wrapper: "lineItem"},
	}}
	child := dto{Name: "ItemDto", Format: "xml", Fields: []field{{Name: "id", Type: "string"}}}
	src, err := render("sample", []dto{d, child})
	if err != nil {
		t.Fatalf("render: %v", err)
	}
	got := string(src)
	for _, want := range []string{
		`xml:"number,attr"`,
		`xml:"date,attr"`,
		`xml:",chardata"`,
		`xml:"lineItems>lineItem"`,
	} {
		if !strings.Contains(got, want) {
			t.Errorf("missing %s in:\n%s", want, got)
		}
	}
	// a plain field stays an element
	if !strings.Contains(got, `xml:"comment,omitempty"`) {
		t.Error("an unmarked field must stay an element")
	}
	// A required attribute is always written...
	if strings.Contains(got, `xml:"number,attr,omitempty"`) {
		t.Error("a required attribute must not carry omitempty")
	}
	// ...but an optional one must be omitted when unset: an empty attribute on
	// a document's identity key can stop iiko finding the document at all.
	if !strings.Contains(got, `xml:"kind,attr,omitempty"`) {
		t.Errorf("an optional attribute must carry omitempty, got:\n%s", got)
	}
}

// XML has no per-field skip hook, so the read-only mark becomes StripReadOnly.
func TestRenderUsesStripForXML(t *testing.T) {
	t.Parallel()
	d := dto{Name: "DocDto", Format: "xml", Fields: []field{
		{Name: "id", Type: "uuid", ReadOnly: true},
		{Name: "comment", Type: "string"},
	}}
	src, err := render("sample", []dto{d})
	if err != nil {
		t.Fatalf("render: %v", err)
	}
	got := string(src)
	if !strings.Contains(got, `xml:"id,omitempty"`) {
		t.Error("an XML DTO must use xml tags")
	}
	if !strings.Contains(got, "func (x *DocDto) StripReadOnly()") {
		t.Error("an XML DTO with read-only fields needs StripReadOnly")
	}
	if strings.Contains(got, "MarshalJSON") {
		t.Error("an XML DTO must not get a JSON marshaler")
	}
}
